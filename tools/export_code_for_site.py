"""Export the notebook code for the site.

Reads model/exs.ipynb, splits it at the markdown cells "## Block N · Title", keeps only the source of
the code cells (no outputs) and writes docs/blocks/code-data.js:
    window.EXS_CODE = { N: [ {code, note} | {md} , ... ] }
A code cell is split at its "# --- ... ---" comment lines; each comment becomes the note of the part
below it. Parts with no such comment get their note from NOTES below (written from the code).
Run from the repository root:  python3 tools/export_code_for_site.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTEBOOK = ROOT / "model" / "exs.ipynb"
OUT = ROOT / "docs" / "blocks" / "code-data.js"

# Notes for code with no "# ---" comment, matched by the start of the part's first line.
NOTES = {
    "WIN = int(SAMPLE_RATE * FRAME_LENGTH)": "Compute the MFCC of one clip: 320-sample window, 160-sample hop, padded so 1 s gives 99 frames of 13 values",
    "class_to_idx = {c: i for i, c in enumerate(CLASSES)}": "Compute the MFCC of every clip, turn labels into class numbers, check the shape is (N, 99, 13)",
    "def build_model(input_shape, n_classes):": "Define the small CNN (two Conv2D + pooling, dropout, softmax) and print its summary",
    "def fresh_model():": "A helper that builds and compiles a fresh model for the sanity checks",
    "model.compile(optimizer=keras.optimizers.Adam(learning_rate=LEARNING_RATE),": "Compile with Adam, then train with early stopping on the validation loss",
    "fig, ax = plt.subplots(1, 2, figsize=(10, 3.5))": "Plot the loss and accuracy curves for train and validation",
    "test_loss, test_acc = model.evaluate(X_test, y_test, verbose=0)": "Evaluate on the held-out speaker: accuracy, confusion matrix and classification report",
    "def representative_data():": "Convert the model to int8 TFLite with a representative dataset and save it with the normalization constants",
    "interp = tf.lite.Interpreter(model_content=tflite_model); interp.allocate_tensors()": "Run the int8 model on the test set and compare its accuracy with the float model",
    "def predict_file(path):": "Predict one WAV file: MFCC, normalize, return the class and its probability",
}
MARK = re.compile(r"^# --- (.*?) ---\s*$")
HEAD = re.compile(r"^#{2,3}\s*Block\s+(\d+)\s*·\s*(.+)$")


def parts(source):
    """Split one code cell at its '# --- note ---' lines."""
    out, cur, note = [], [], None
    for line in source.splitlines():
        m = MARK.match(line)
        if m:
            if cur: out.append((note, cur))
            cur, note = [line], m.group(1)
        else:
            cur.append(line)
    if cur: out.append((note, cur))
    res = []
    for note, lines in out:
        code = "\n".join(lines).strip("\n")
        if not code.strip(): continue
        if note is None:
            first = code.splitlines()[0]
            note = next((v for k, v in NOTES.items() if first.startswith(k)), None)
            if note is None: raise SystemExit(f"no note for a code part starting with: {first!r}")
        res.append({"code": code, "note": note})
    return res


def main():
    cells = json.loads(NOTEBOOK.read_text(encoding="utf-8"))["cells"]
    blocks, n = {}, None
    for c in cells:
        src = "".join(c["source"])
        if c["cell_type"] == "markdown":
            m = HEAD.match(src.splitlines()[0]) if src.strip() else None
            if m:
                n = int(m.group(1)); blocks[n] = []
                rest = "\n".join(src.splitlines()[1:]).strip()
                if rest: blocks[n].append({"md": rest})
            elif n is not None and src.strip():
                blocks[n].append({"md": src.strip()})
        elif c["cell_type"] == "code" and n is not None:
            blocks[n].extend(parts(src))   # outputs are never read
    OUT.write_text("/* Generated by tools/export_code_for_site.py from model/exs.ipynb. Do not edit by hand. */\n"
                   "window.EXS_CODE = " + json.dumps(blocks, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{k}: {sum('code' in x for x in v)} code" for k, v in sorted(blocks.items())))


if __name__ == "__main__":
    main()
